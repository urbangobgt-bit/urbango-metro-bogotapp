/**
 * Helper dinámico para resolver noticias localizadas reactivamente según el idioma activo
 * @param {string} lang - 'es' | 'en' | 'pt' | 'zh'
 */
export const getLocalizedNews = (lang = 'es') => {
  const l = (lang || 'es').toLowerCase();
  const validLang = ['es', 'en', 'pt', 'zh'].includes(l) ? l : 'es';

  return Object.values(NEWS_DATABASE_MULTILINGUAL).map((item) => {
    const loc = item[validLang] || item.es;
    return {
      id: item.id,
      img: item.img,
      author: item.author,
      source: item.source,
      url: item.url,
      category: item.categoryKey,
      categoryKey: item.categoryKey,
      isLive: item.isLive,
      isBreaking: item.isBreaking,
      readMin: item.readMin,
      
      // Localized fields
      title: loc.title,
      titulo: loc.title,
      subtitle: loc.subtitle,
      subtitulo: loc.subtitle,
      excerpt: loc.excerpt,
      resumen: loc.excerpt,
      categoryLabel: loc.categoryLabel,
      categoria: loc.category,
      localidad: loc.localidad,
      date: loc.date,
      fecha: loc.date,
      readTime: loc.readTime,
      tiempoLectura: loc.readTime,
      readMore: loc.readMore,
      content: loc.fullContent,
      fullText: loc.fullContent,
      fullContent: loc.fullContent,
      contenidoCompleto: loc.fullContent
    };
  });
};

